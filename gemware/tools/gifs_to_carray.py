#!/usr/bin/env python3
"""Package the workspace GIF animations as raw C arrays for LVGL's lv_gif.

Frames are rotated (default 180 deg) inside the GIF data itself, so the widget
needs no runtime transform. Also emits per-animation total duration so callers
can time one-shot reactions.

Usage:
    python3 tools/gifs_to_carray.py [rotation] [--input-dir PATH]
"""
import argparse
import io
from pathlib import Path

from PIL import Image

PROJECT_DIR = Path(__file__).resolve().parents[1]
DEFAULT_INPUT_DIR = PROJECT_DIR.parent / "animations"
OUT_DIR = PROJECT_DIR / "gemware" / "main"

ROTATIONS = {
    "90": Image.ROTATE_90,
    "180": Image.ROTATE_180,
    "270": Image.ROTATE_270,
}


def load_all(input_dir: Path) -> list[tuple[str, bytes]]:
    """Load all GIFs, keeping idle first as the UI's fallback animation."""
    if not input_dir.is_dir():
        raise SystemExit(f"Animation directory does not exist: {input_dir}")

    anims = [(path.stem, path.read_bytes()) for path in input_dir.glob("*.gif")]
    if not anims:
        raise SystemExit(f"No GIF files found in: {input_dir}")
    if not any(name == "idle" for name, _ in anims):
        raise SystemExit(f"Missing required idle.gif in: {input_dir}")
    return sorted(anims, key=lambda anim: (anim[0] != "idle", anim[0]))


def process(data: bytes, rotation: str) -> tuple[bytes, int]:
    im = Image.open(io.BytesIO(data))
    frames, durs = [], []
    for i in range(im.n_frames):
        im.seek(i)
        durs.append(im.info.get("duration", 100))
        fr = im.convert("RGBA")
        if rotation != "0":
            fr = fr.transpose(ROTATIONS[rotation])
        frames.append(fr)
    buf = io.BytesIO()
    frames[0].save(
        buf,
        format="GIF",
        save_all=True,
        append_images=frames[1:],
        duration=durs,
        loop=0,
        disposal=2,
        transparency=0,
        optimize=False,
    )
    return buf.getvalue(), sum(durs)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rotation", nargs="?", choices=("0", "90", "180", "270"), default="180")
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_INPUT_DIR)
    args = parser.parse_args()
    rotation = args.rotation
    anims = load_all(args.input_dir)

    c = [
        f"/* Auto-generated by tools/gifs_to_carray.py (rotate={rotation}). */",
        '#include "lvgl.h"',
        '#include "gemmi_anims.h"',
        "",
    ]
    entries = []
    generated_size = 0
    for name, data in anims:
        ident = name.replace("-", "_")
        raw, total_ms = process(data, rotation)
        generated_size += len(raw)
        c.append(f"static const uint8_t gemmi_{ident}_gif[{len(raw)}] = {{")
        for i in range(0, len(raw), 16):
            c.append("    " + ", ".join(f"0x{b:02x}" for b in raw[i : i + 16]) + ",")
        c.append("};")
        c.append(
            f"static const lv_image_dsc_t gemmi_{ident}_dsc = {{\n"
            f"    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"    .header.cf = LV_COLOR_FORMAT_RAW,\n"
            f"    .data_size = sizeof(gemmi_{ident}_gif),\n"
            f"    .data = gemmi_{ident}_gif,\n"
            f"}};\n"
        )
        entries.append(f'    {{ "{name}", &gemmi_{ident}_dsc, {total_ms} }},')

    c.append(f"const gemmi_anim_t gemmi_anims[{len(entries)}] = {{")
    c += entries
    c.append("};")
    c.append("const uint32_t gemmi_anims_count = sizeof(gemmi_anims) / sizeof(gemmi_anims[0]);")

    h = """/* Auto-generated by tools/gifs_to_carray.py. */
#pragma once
#include "lvgl.h"

typedef struct {
    const char * name;
    const lv_image_dsc_t * dsc;
    uint16_t total_ms;
} gemmi_anim_t;

#define GEMMI_ANIM_IDLE 0

extern const gemmi_anim_t gemmi_anims[];
extern const uint32_t gemmi_anims_count;
"""

    (OUT_DIR / "gemmi_anims.c").write_text("\n".join(c) + "\n")
    (OUT_DIR / "gemmi_anims.h").write_text(h)
    names = [n for n, _ in anims]
    print(f"wrote {OUT_DIR}/gemmi_anims.{{c,h}} — {len(anims)} anims, ~{generated_size // 1024}KB generated")
    print(names)


if __name__ == "__main__":
    main()
