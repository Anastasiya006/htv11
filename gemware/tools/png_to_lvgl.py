#!/usr/bin/env python3
"""Convert PNG sprites to LVGL ARGB8888 C arrays embedded in flash.

The ESP32 build has no PSRAM and keeps the LVGL image cache disabled, so
decoding PNGs at draw time allocates from a heap the animated GIF keeps
fragmenting. Under pressure the re-decode fails and the sprite disappears a
few seconds after it first renders. Pre-decoding to LVGL's native ARGB8888
layout stores the pixels in `.rodata` (flash) and removes runtime decoding
entirely, so the shop art can never fail to draw.

Each `.inc` keeps the xxd-style symbol name the firmware already references,
but holds raw ARGB8888 bytes (B, G, R, A per pixel, matching lv_color32_t)
instead of the encoded PNG. The arrays are `const` so they land in flash, and
4-byte aligned for the 32-bit pixel reads.

Usage: python3 gemware/tools/png_to_lvgl.py gemware/gemware/main/halloween_assets
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

REPO_ROOT = Path(__file__).resolve().parents[2]


def symbol_for(png: Path) -> str:
    """Reproduce xxd -i naming: repo-relative path with non-alnum -> '_'."""
    relative = png.resolve().relative_to(REPO_ROOT).as_posix()
    return "".join(c if c.isalnum() else "_" for c in relative)


def emit(png: Path) -> None:
    image = Image.open(png).convert("RGBA")
    width, height = image.size
    pixels = image.load()
    symbol = symbol_for(png)
    body = bytearray()
    for y in range(height):
        for x in range(width):
            r, g, b, a = pixels[x, y]
            body += bytes((b, g, r, a))  # LVGL ARGB8888 is B, G, R, A in memory.

    lines = [
        f"/* Generated by gemware/tools/png_to_lvgl.py from {png.name}",
        f" * {width}x{height} ARGB8888 ({len(body)} bytes), native LVGL layout. */",
        f"static const unsigned char __attribute__((aligned(4))) {symbol}[] = {{",
    ]
    for offset in range(0, len(body), 12):
        chunk = body[offset:offset + 12]
        lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.append("};")

    out = png.with_suffix(".inc")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out.resolve().relative_to(REPO_ROOT)}: {width}x{height} -> {len(body)} bytes")


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    root = Path(argv[1])
    pngs = sorted(root.rglob("*.png"))
    if not pngs:
        print(f"No PNGs under {root}")
        return 1
    for png in pngs:
        emit(png)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
