#!/usr/bin/env python3
"""Extract a GIF (embedded in the tamagotchi demo HTML or a plain .gif) into
LVGL RGB565 C arrays for the ESP32 TFT app.

Usage:
    python3 tools/gif_to_lvgl.py <animation-name> [rotation] [bg]

Reads ~/Downloads/tamagotchi-demo.html, pulls the named animation's data URI,
composites each frame onto `bg` (default black), rotates it (default 180 deg),
and writes main/gemmi_<name>.c + .h next to the app sources.
"""
import base64
import re
import sys
from pathlib import Path

from PIL import Image

HTML_PATH = Path.home() / "Downloads" / "tamagotchi-demo.html"
OUT_DIR = Path(__file__).resolve().parents[1] / "gemware" / "main"

ROTATIONS = {
    "0": Image.ROTATE_90,      # placeholder, handled below
    "90": Image.ROTATE_90,
    "180": Image.ROTATE_180,
    "270": Image.ROTATE_270,
}


def extract_gif(name: str) -> bytes:
    html = HTML_PATH.read_text()
    m = re.search(
        r'\{"name":\s*"' + re.escape(name) + r'",\s*"src":\s*"data:image/gif;base64,([^"]+)"',
        html,
    )
    if not m:
        names = re.findall(r'\{"name":\s*"([^"]+)",\s*"src":\s*"data:image', html)
        sys.exit(f"animation '{name}' not found; available: {names}")
    return base64.b64decode(m.group(1))


def main() -> None:
    name = sys.argv[1] if len(sys.argv) > 1 else "idle"
    rotation = sys.argv[2] if len(sys.argv) > 2 else "180"
    bg_color = (255, 255, 255) if (len(sys.argv) > 3 and sys.argv[3] == "white") else (0, 0, 0)

    gif_path = Path(f"/tmp/gemmi_{name}.gif")
    gif_path.write_bytes(extract_gif(name))
    im = Image.open(gif_path)

    frames = []
    durations = []
    for i in range(im.n_frames):
        im.seek(i)
        durations.append(im.info.get("duration", 100))
        frame = im.convert("RGBA")
        bg = Image.new("RGB", frame.size, bg_color)
        bg.paste(frame, (0, 0), frame)
        if rotation != "0":
            bg = bg.transpose(ROTATIONS[rotation])
        frames.append(bg)

    w, h = frames[0].size
    stem = f"gemmi_{name}"

    c_lines = [
        f"/* Auto-generated by tools/gif_to_lvgl.py from {gif_path.name} "
        f"({len(frames)} frames, {w}x{h}, rotate={rotation}, bg={bg_color}). */",
        '#include "lvgl.h"',
        f'#include "{stem}.h"',
        "",
    ]
    for i, fr in enumerate(frames):
        px = []
        rgb = fr.tobytes()
        for j in range(0, len(rgb), 3):
            r, g, b = rgb[j], rgb[j + 1], rgb[j + 2]
            v = (r & 0xF8) << 8 | (g & 0xFC) << 3 | b >> 3
            px += [f"0x{v & 0xFF:02x}", f"0x{v >> 8:02x}"]
        c_lines.append(f"static const uint8_t {stem}_f{i}_map[{w * h * 2}] = {{")
        for j in range(0, len(px), 16):
            c_lines.append("    " + ", ".join(px[j : j + 16]) + ",")
        c_lines.append("};")
        c_lines.append(
            f"const lv_image_dsc_t {stem}_f{i} = {{\n"
            f"    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"    .header.cf = LV_COLOR_FORMAT_RGB565,\n"
            f"    .header.w = {w},\n"
            f"    .header.h = {h},\n"
            f"    .header.stride = {w * 2},\n"
            f"    .data_size = {w * h * 2},\n"
            f"    .data = {stem}_f{i}_map,\n"
            f"}};\n"
        )

    c_lines.append(
        f"const lv_image_dsc_t *const {stem}_frames[{len(frames)}] = {{"
    )
    c_lines += [f"    &{stem}_f{i}," for i in range(len(frames))]
    c_lines.append("};\n")
    c_lines.append(
        f"const uint16_t {stem}_durations_ms[{len(frames)}] = {{"
        + ", ".join(str(d) for d in durations)
        + "};"
    )

    h_text = f"""/* Auto-generated by tools/gif_to_lvgl.py. */
#pragma once
#include "lvgl.h"

#define {stem.upper()}_FRAME_COUNT {len(frames)}

extern const lv_image_dsc_t *const {stem}_frames[{len(frames)}];
extern const uint16_t {stem}_durations_ms[{len(frames)}];
"""

    (OUT_DIR / f"{stem}.c").write_text("\n".join(c_lines) + "\n")
    (OUT_DIR / f"{stem}.h").write_text(h_text)
    print(f"wrote {OUT_DIR}/{stem}.{{c,h}}  "
          f"{len(frames)} frames {w}x{h} = {len(frames) * w * h * 2} bytes, "
          f"durations={durations}")


if __name__ == "__main__":
    main()
